/**
 * Получить эмодзи для сна на основе тегов
 */
export function getEmojiFromTags(tags: string[]): string | null {
  if (!tags || tags.length === 0) return null
  
  // Проверяем теги в нижнем регистре
  const lowerTags = tags.map(tag => tag.toLowerCase().trim())
  
  // Ищем точное совпадение
  for (const tag of lowerTags) {
    if (TAG_EMOJI_MAP[tag]) {
      return TAG_EMOJI_MAP[tag]
    }
  }
  
  // Ищем частичное совпадение
  for (const tag of lowerTags) {
    for (const [key, emoji] of Object.entries(TAG_EMOJI_MAP)) {
      if (tag.includes(key) || key.includes(tag)) {
        return emoji
      }
    }
  }
  
  return null
}

/**
 * Получить эмодзи для сна на основе контента (fallback)
 */
export function getEmojiFromContent(content: string): string {
  const lowerContent = content.toLowerCase()
  
  // Проверяем ключевые слова в контенте
  for (const [key, emoji] of Object.entries(TAG_EMOJI_MAP)) {
    if (lowerContent.includes(key)) {
      return emoji
    }
  }
  
  // Стандартные проверки
  if (lowerContent.includes('полёт') || lowerContent.includes('лет')) return '✈️'
  if (lowerContent.includes('дом')) return '🏘️'
  if (lowerContent.includes('лес')) return '🌳'
  if (lowerContent.includes('темнота') || lowerContent.includes('преследова')) return '🌑'
  if (lowerContent.includes('вода') || lowerContent.includes('море')) return '🌊'
  if (lowerContent.includes('город')) return '🏙️'
  
  return '💭'
}

